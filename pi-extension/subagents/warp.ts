/**
 * Warp terminal backend for pi-interactive-subagents.
 *
 * Warp is not a multiplexer and exposes no `send-keys` / `capture-pane` style
 * CLI, so this backend reaches class-1 parity through a **surface directory
 * handshake** instead of keystroke injection:
 *
 *   1. We allocate a surface directory and drop `.pi-warp-surface` + `surface.json`.
 *   2. We ask Warp to open a tab whose cwd IS that directory
 *      (`warp://action/new_tab?path=<surface dir>` — works on Linux, Windows and
 *      macOS, needs no Warp "Scripting" toggle).
 *   3. A tiny shell hook (installed once into bashrc/zshrc/fish/PowerShell
 *      profile — see `scripts/install-warp-hook.mjs`) notices the marker, and
 *      execs `pi-warp-bootstrap`, which becomes the pane driver:
 *        - runs the requested command under a pty (`script -qfe` on Unix),
 *        - mirrors everything to `out.log`  → gives us `readScreen`,
 *        - feeds `in.fifo` into the child's stdin → gives us `sendCommand` /
 *          `sendEscape`,
 *        - writes `__SUBAGENT_DONE_<code>__` + `status.json` on exit → gives us
 *          `pollForExit` crash detection with the existing sentinel contract.
 *
 * Optional niceties (rename/close/split/focus real Warp panes) go through
 * Warp's hidden local-control CLI `warpctrl` when the user has enabled
 * Settings > Scripting. `warpctrl` is *not* required, and is currently not
 * published on Windows, so every code path degrades gracefully.
 *
 * See docs/adr/0011-warp-terminal-class-1-backend.md.
 */
