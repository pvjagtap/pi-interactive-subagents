const execFileAsync = promisify(execFile);

/** Bumped when the on-disk surface handshake changes shape. */
export const WARP_SURFACE_PROTOCOL = 1;

const HERE = dirname(fileURLToPath(import.meta.url));

/** Files that make up one surface directory. */
export const SURFACE_FILES = {
  marker: ".pi-warp-surface",
  spec: "surface.json",
  env: "surface.env",
  status: "status.json",
  log: "out.log",
  input: process.platform === "win32" ? "in.cmd" : "in.fifo",
} as const;

/** POSIX single-quote escaping: the only safe way to hand data to a shell. */
export function shQuote(value: string): string {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

/** Render surface.json as a file the pane bootstrap can simply `.` (source). */
export function renderSurfaceEnv(spec: WarpSurfaceSpec): string {
  const lines = [
    "# generated by pi-interactive-subagents — do not edit",
    `PI_WARP_PROTOCOL=${shQuote(String(spec.protocol))}`,
    `PI_WARP_ID=${shQuote(spec.id)}`,
    `PI_WARP_NAME=${shQuote(spec.name)}`,
    `PI_WARP_CWD=${shQuote(spec.cwd)}`,
    `PI_WARP_COMMAND=${shQuote(spec.command ?? "")}`,
    `PI_WARP_LOG=${shQuote(spec.log)}`,
    `PI_WARP_INPUT=${shQuote(spec.input)}`,
    `PI_WARP_STATUS=${shQuote(spec.status)}`,
  ];
  for (const [key, value] of Object.entries(spec.env ?? {})) {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) continue; // never emit a bogus name
    lines.push(`export ${key}=${shQuote(value)}`);
  }
  return lines.join("\n") + "\n";
}

export interface WarpSurfaceSpec {
  protocol: number;
  id: string;
  name: string;
  /** Directory the pane should `cd` into before running `command`. */
  cwd: string;
  /** Command executed by the bootstrap (a script path, usually). */
  command: string | null;
  /** Absolute paths, resolved for the pane's shell. */
  log: string;
  input: string;
  status: string;
  createdAt: number;
  /** Environment injected into the pane before `command` runs. */
  env: Record<string, string>;
}

export interface WarpSurfaceStatus {
  id: string;
  pid?: number;
  /** pid of the command running under the pty, when the bootstrap reports it. */
  childPid?: number;
  /** "starting" | "running" | "exited" */
  state: string;
  exitCode?: number;
  updatedAt?: number;
  /** Set when the exit was inferred from a dead pid rather than a clean trap. */
  stale?: boolean;
  /** Pane geometry reported by the bootstrap, used to render the transcript. */
  rows?: number;
  cols?: number;
  /** Sanitised tab title the bootstrap asserted (diagnostics; OSC output is not logged). */
  title?: string;
  /** Warp pane id, filled in by `warpctrl` when local control is available. */
  paneId?: string;
}

