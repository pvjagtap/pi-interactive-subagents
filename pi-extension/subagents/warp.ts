function surfacesRoot(): string {
  return join(warpStateDir(), "surfaces");
}

export function surfaceDir(id: string): string {
  return join(surfacesRoot(), id);
}

function newSurfaceId(): string {
  return `w${Date.now().toString(36)}${Math.random().toString(36).slice(2, 7)}`;
}

/** Bootstrap script shipped with the package, per pane shell family. */
export function bootstrapScriptPath(): string {
  const file = process.platform === "win32" ? "pi-warp-bootstrap.ps1" : "pi-warp-bootstrap.sh";
  return join(HERE, "warp-bootstrap", file);
}

export interface CreateWarpSurfaceOptions {
  /** Working directory the pane should land in. Defaults to process.cwd(). */
  cwd?: string;
  /** Command to execute in the pane. When omitted the pane opens an idle shell. */
  command?: string;
  /** Extra environment for the pane. */
  env?: Record<string, string>;
  /** `tab` (default) gives each subagent full width; `split` uses warpctrl. */
  mode?: "tab" | "split";
  /** Split direction, only meaningful with warpctrl available. */
  direction?: "left" | "right" | "up" | "down";
}

/**
 * Allocate a surface directory + ask Warp to open a tab on it.
 * Returns the surface id, which doubles as the pane handle used by every other
 * function in this module.
 */
export function createWarpSurface(name: string, options: CreateWarpSurfaceOptions = {}): string {
  const id = newSurfaceId();
  const dir = surfaceDir(id);
  mkdirSync(dir, { recursive: true });

  const spec: WarpSurfaceSpec = {
    protocol: WARP_SURFACE_PROTOCOL,
    id,
    name,
    cwd: options.cwd ?? process.cwd(),
    command: options.command ?? null,
    log: join(dir, SURFACE_FILES.log),
    input: join(dir, SURFACE_FILES.input),
    status: join(dir, SURFACE_FILES.status),
    createdAt: Date.now(),
    env: {
      PI_SUBAGENT_SURFACE: id,
      PI_SUBAGENT_SURFACE_DIR: dir,
      PI_WARP_SURFACE_NAME: name,
      ...(options.env ?? {}),
    },
  };

  writeFileSync(join(dir, SURFACE_FILES.spec), JSON.stringify(spec, null, 2));
  // Shell-sourceable twin of surface.json. The bootstrap used to parse JSON
  // with sed, which silently truncated any value containing a quote or
  // backslash — and those values are then executed. Quoting here, once, in a
  // language that knows the data, removes that whole class of bug.
  writeFileSync(join(dir, SURFACE_FILES.env), renderSurfaceEnv(spec));
  writeFileSync(join(dir, SURFACE_FILES.log), "");
  writeStatus(id, { id, state: "starting", updatedAt: Date.now() });
  // Marker last: the hook only fires once the spec is complete.
  writeFileSync(join(dir, SURFACE_FILES.marker), `${WARP_SURFACE_PROTOCOL}\n`);

  if (options.mode === "split" && isWarpctrlAvailable()) {
    // warpctrl splits the *active* pane and the new pane inherits the active
    // pane's cwd, so we cd via the hook marker copied into the split's cwd.
    warpctrl(["pane", "split", "--direction", options.direction ?? "right"]);
    // The split inherits our cwd; hand it the surface dir explicitly.
    openWarpTab(dir);
  } else {
    openWarpTab(dir);
  }

  if (isWarpctrlAvailable()) {
    try {
      warpctrl(["pane", "rename", name]);
    } catch {
      /* cosmetic */
    }
  }
  return id;
}

/** Ask the running Warp app to open a new tab rooted at `path`. */
export function openWarpTab(path: string): void {
  // Escape hatch for tests / dry-runs: prepare the surface but do not open UI.
  if (process.env.PI_WARP_NO_LAUNCH === "1") return;
  const url = `warp://action/new_tab?path=${encodeURIComponent(path)}`;
  const bin = getWarpBin();
  if (bin) {
    detach(bin, [url]);
    return;
  }
  if (process.platform === "win32") {
    detach("cmd", ["/c", "start", "", url]);
  } else if (process.platform === "darwin") {
    detach("open", [url]);
  } else {
    detach("xdg-open", [url]);
  }
}

function detach(cmd: string, args: string[]): void {
  const child = spawn(cmd, args, { detached: true, stdio: "ignore" });
  child.unref();
}

function warpctrl(args: string[]): string {
  const bin = getWarpctrlBin();
  if (!bin) throw new Error("warpctrl is not available");
  return execFileSync(bin, args, { encoding: "utf8", timeout: 5000 });
}

